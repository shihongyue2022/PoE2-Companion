import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('poe2-workbench-loadout-v1')));
try {
  await page.route('**/api/workbench/trade-log*', (route) => route.fulfill({ json: { ok: true, found: false, events: [], truncated: false } }));
  await page.route('**/api/workbench/pob/builds', (route) => route.fulfill({ json: { ok: true, installed: false, builds: [] } }));
  await page.goto(process.env.WORKBENCH_URL ?? 'http://127.0.0.1:5173/?companion=1');
  const initial = await page.evaluate(async () => {
    const { threeSkillRoutineState } = await import('/src/workbench/fixtures/skillAffixGuide.ts');
    const state = threeSkillRoutineState();
    localStorage.setItem('poe2-workbench-loadout-v1', JSON.stringify(state));
    return state;
  });
  await page.reload();
  const panel = page.getByRole('region', { name: '主输出与智能配装' });
  const bar = panel.getByRole('group', { name: '实际使用的技能组' });
  await expect(bar.locator('.sr-slot')).toHaveCount(0);
  await panel.getByRole('button', { name: '编辑技能组' }).click();
  await panel.getByRole('button', { name: '采用旋风三技能组合' }).click();
  await expect(bar.locator('.sr-slot')).toHaveCount(3);
  assert.deepEqual((await saved()).goals.skillBar.map((entry) => entry.name), ['Twister', 'Explosive Spear', 'Whirling Slash']);
  assert.equal((await saved()).goals.mainSkill.name, 'Twister');
  assert.equal((await saved()).source.combat.mainGroup, 7);
  await panel.getByRole('button', { name: '收起技能库' }).click();
  await mkdir('artifacts/workbench', { recursive: true });
  await panel.screenshot({ path: 'artifacts/workbench/skill-routine-desktop.png' });
  assert((await panel.boundingBox()).height < 250, 'default panel must remain compact');
  const goalsBeforeInspect = (await saved()).goals;
  await bar.getByRole('button', { name: '展开技能：爆炸长矛', exact: true }).click();
  const guide = panel.getByRole('region', { name: '技能增伤与装备检索' });
  await expect(guide.getByRole('group', { name: '查阅辅助机制' })).toContainText('火焰穿透');
  await expect(guide.getByRole('group', { name: '查阅辅助机制' })).not.toContainText('投射物加速');
  assert.deepEqual((await saved()).goals, goalsBeforeInspect);
  await guide.getByRole('button', { name: '收起增伤与装备' }).click();
  // Native HTML drag, including the image inside the card: data must refer to the skill, not an image URL.
  await bar.locator('.sr-slot').first().dragTo(bar.locator('.sr-add'));
  await expect.poll(async () => (await saved()).goals.skillBar.map((entry) => entry.name)).toEqual(['Explosive Spear', 'Whirling Slash', 'Twister']);
  assert.equal((await saved()).goals.mainSkill.name, 'Twister');
  await page.reload();
  await expect(bar.locator('.sr-slot')).toHaveCount(3);
  assert.deepEqual((await saved()).goals.skillBar.map((entry) => entry.name), ['Explosive Spear', 'Whirling Slash', 'Twister']);
  await panel.getByRole('button', { name: '编辑技能组' }).click();
  await bar.locator('.sr-slot').last().dragTo(panel.locator('.sr-library'));
  await expect(bar.locator('.sr-slot')).toHaveCount(2);
  assert.equal((await saved()).goals.mainSkill.name, 'Explosive Spear');
  await page.setViewportSize({ width: 390, height: 844 });
  const library = panel.getByRole('group', { name: '可拖入的技能库' });
  await library.getByRole('button', { name: /添加技能：旋风 ·/ }).click();
  await expect(bar.locator('.sr-slot')).toHaveCount(3);
  await panel.getByRole('button', { name: '前移旋风' }).click();
  await expect.poll(async () => (await saved()).goals.skillBar.map((entry) => entry.name)).toEqual(['Explosive Spear', 'Twister', 'Whirling Slash']);
  await panel.getByRole('button', { name: '收起技能库' }).click();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await panel.screenshot({ path: 'artifacts/workbench/skill-routine-mobile.png' });
  await bar.getByRole('button', { name: '展开技能：旋风', exact: true }).click();
  await expect(guide.getByRole('group', { name: '查阅辅助机制' })).toContainText('投射物加速');
  await guide.getByRole('button', { name: '作为装备检索重点' }).click();
  assert.equal((await saved()).goals.mainSkill.name, 'Twister');
  assert.deepEqual((await saved()).goals.skillBar.map((entry) => entry.name), ['Explosive Spear', 'Twister', 'Whirling Slash']);
  assert.deepEqual((await saved()).slots, initial.slots);
  assert.deepEqual((await saved()).source, initial.source);
  assert.deepEqual(errors, []);
  console.log('PASS compact three-skill routine, native drag reorder/removal, click-to-add and mobile arrows, per-skill supports, explicit search focus, unchanged PoB snapshot and persistence');
} finally { await browser.close(); }
