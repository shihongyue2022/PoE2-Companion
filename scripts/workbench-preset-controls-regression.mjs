import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = []; page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.route('**/api/workbench/estimate', (route) => route.fulfill({ json: { ok: true, total: 0, fetched: 0, priced: 0, groups: [], listings: [], sampledAt: new Date().toISOString(), cached: false, warnings: [], url: 'https://www.pathofexile.com/trade2' } }));
  await page.goto(process.env.WORKBENCH_URL ?? 'http://127.0.0.1:5173/?companion=1');
  await expect(page.getByRole('region', { name: '角色全身装备' })).toBeVisible();
  await page.evaluate(async () => {
    const { damageState } = await import('/src/workbench/fixtures/damageGoal.ts');
    const { BOOTS_SAMPLE } = await import('/src/workbench/fixtures/fullGear.ts');
    const { equipmentSignature } = await import('/src/workbench/characterPanel.ts');
    const state = damageState(); state.slots = { boots: BOOTS_SAMPLE };
    state.character.values.life = 1530;
    state.character.equipmentSignature = state.source.equipmentSignature = equipmentSignature(state.slots);
    localStorage.setItem('poe2-workbench-loadout-v1', JSON.stringify(state));
  });
  await page.reload();
  const loadout = page.getByRole('region', { name: '角色全身装备' });
  await loadout.getByRole('navigation').getByRole('button', { name: /^校准抗性/ }).click();
  const calibration = loadout.locator('.lo-calibration');
  await expect(calibration.getByText('1530', { exact: true }).first()).toBeVisible();
  await expect(calibration.getByLabel('角色面板最大生命', { exact: true })).toBeHidden();
  await calibration.getByLabel('角色火焰抗性上限档位').selectOption('80');
  await calibration.getByRole('button', { name: '保存当前游戏面板基准' }).click();
  await expect(loadout.getByRole('region', { name: '当前整套抗性' })).toContainText('火焰抗性：80% / 80%');
  await loadout.getByText('设置升级目标', { exact: false }).click();
  await loadout.getByLabel('火焰抗性装备目标档位').selectOption('90');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('poe2-workbench-loadout-v1')).goals.minimums.fireResistance), 90);
  await loadout.getByRole('button', { name: /^鞋靴：/ }).click();
  await loadout.getByRole('button', { name: '估价这件装备', exact: true }).click();
  const panel = page.getByRole('region', { name: '全物品查价' });
  await panel.getByRole('button', { name: /综合找升级/ }).click();
  await panel.getByLabel('升级预算上限档位').selectOption('25');
  await expect(panel.getByLabel('升级预算上限', { exact: true })).toBeHidden();
  const conditions = panel.locator('.wb-search-conditions'); await conditions.locator(':scope > summary').click();
  const lifeChoice = panel.locator('select[aria-label*="生命"][aria-label$="搜索档位"]').filter({ has: page.locator('option[value="t2"]') }).first();
  const lifeRow = lifeChoice.locator('xpath=ancestor::div[contains(@class,"wb-trade-filter")][1]');
  await lifeRow.getByRole('checkbox').check();
  await expect(lifeChoice).toBeEnabled();
  await lifeChoice.selectOption('t2');
  await expect(lifeChoice).toHaveValue('t2');
  const tierMinimum = Number(await lifeRow.locator('input[aria-label$="下限"]').inputValue());
  const query = JSON.parse(new URL(await panel.getByRole('link', { name: '打开升级候选搜索', exact: true }).getAttribute('href')).searchParams.get('q'));
  assert.equal(query.query.filters.trade_filters.filters.price.max, 25);
  assert(tierMinimum > 0 && query.query.stats.filter((group) => group.type !== 'weight').flatMap((group) => group.filters).some((filter) => filter.value?.min === tierMinimum));
  await expect(panel.locator('.wb-trade-manual input').first()).toBeHidden();
  await expect(panel.getByLabel('全装备交易赛季', { exact: true })).toHaveJSProperty('tagName', 'SELECT');
  await mkdir('artifacts/workbench', { recursive: true });
  await panel.screenshot({ path: 'artifacts/workbench/preset-controls-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await panel.screenshot({ path: 'artifacts/workbench/preset-controls-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('PASS imported panel prefill, cap and resistance-buffer presets, budget preset, verified per-affix T2 threshold, folded exact fields and mobile layout');
} finally { await browser.close(); }
