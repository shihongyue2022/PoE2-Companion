import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = []; page.on('pageerror', (error) => errors.push(error.message));
let updatedXml = '';
const stamp = '2026-10-23T01:00:00Z';
try {
  await page.route('**/api/workbench/pob/builds', (route) => route.fulfill({ json: { ok: true, installed: true, builds: [{ id: 'a'.repeat(64), name: 'Current.xml', modifiedAt: stamp }] } }));
  await page.route('**/api/workbench/pob/build', (route) => route.fulfill({ json: { ok: true, xml: updatedXml, name: 'Current.xml', modifiedAt: stamp } }));
  await page.goto(process.env.WORKBENCH_URL ?? 'http://127.0.0.1:5173/?companion=1');
  updatedXml = await page.evaluate(async () => {
    const { dualWeaponsXml, firstWeapon, secondWeapon } = await import('/src/workbench/fixtures/dualWeapons.ts');
    const { parsePobXml, previewPob, pobImportSource } = await import('/src/workbench/pobImport.ts');
    const { emptyLoadout, serializeLoadout } = await import('/src/workbench/loadout.ts');
    const { applyPobLoadout } = await import('/src/workbench/loadoutIntegration.ts');
    const spear = 'Rarity: Unique\nThe Ordained\nSolemn Spear\n--------\nPhysical Damage: 100-200\nAttacks per Second: 1.50\n--------\n220% increased Physical Damage';
    const original = dualWeaponsXml.replace(firstWeapon, spear), document = parsePobXml(original), preview = previewPob(document, '1', false);
    const source = pobImportSource(document, '1', false, preview.slots, { name: 'Current.xml', modifiedAt: '2026-10-23T00:00:00Z' });
    localStorage.setItem('poe2-workbench-loadout-v1', serializeLoadout(applyPobLoadout(emptyLoadout(), preview.slots, source)));
    return original.replace('220% increased Physical Damage', '303% increased Physical Damage').replace('Physical Damage: 100-200', 'Physical Damage: 150-250').replace(secondWeapon, secondWeapon.replace('+20 to maximum Life', '+30 to maximum Life'));
  });
  await page.reload();
  const loadout = page.getByRole('region', { name: '角色全身装备' });
  const refresh = loadout.getByRole('button', { name: '保存后重新读取', exact: true });
  await refresh.click();
  const preview = loadout.locator('.lo-pob-preview');
  await expect(preview.getByRole('article', { name: '武器组 I · 主手更新详情' })).toContainText('增加220%物理伤害');
  await expect(preview.getByRole('article', { name: '武器组 I · 主手更新详情' })).toContainText('增加303%物理伤害');
  await expect(preview.getByRole('row', { name: /武器物理 DPS/ })).toContainText('+75');
  await expect(preview.getByRole('article', { name: '武器组 II · 主手更新详情' })).toContainText('最大生命');
  await preview.getByRole('button', { name: /确认替换整套装备/ }).click();
  const first = await page.evaluate(() => JSON.parse(localStorage.getItem('poe2-workbench-loadout-v1')));
  assert.equal(first.lastImport.equipmentChanges, 2);
  await refresh.click();
  await expect(preview.getByRole('region', { name: '整套装备更新对照' })).toContainText('装备栏位没有实际数值变化');
  await preview.getByRole('button', { name: /确认替换整套装备/ }).click();
  const repeated = await page.evaluate(() => JSON.parse(localStorage.getItem('poe2-workbench-loadout-v1')));
  assert.equal(repeated.lastImport.equipmentChanges, 0);
  assert.deepEqual(repeated.previous, first.previous);
  await page.reload();
  await loadout.locator('summary').filter({ hasText: '角色来源与更新记录' }).click();
  const history = loadout.locator('details').filter({ has: page.locator(':scope > summary', { hasText: '最近一次整套更新对照' }) });
  await history.locator(':scope > summary').click();
  await expect(history.getByRole('row', { name: /武器物理 DPS/ })).toContainText('+75');
  await expect(history.getByRole('article', { name: '武器组 II · 主手更新详情' })).toContainText('最大生命');
  await mkdir('artifacts/workbench', { recursive: true });
  await history.screenshot({ path: 'artifacts/workbench/equipment-update-details-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await history.screenshot({ path: 'artifacts/workbench/equipment-update-details-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('PASS same-name roll and weapon DPS details, standby weapon changes, repeated refresh history and mobile layout');
} finally { await browser.close(); }
