import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.WORKBENCH_URL ?? 'http://127.0.0.1:4322/apps/poe2-companion/';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], apiRequests = [], missing = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/\/api\//.test(new URL(request.url()).pathname)) apiRequests.push(request.url()); });
page.on('response', response => { if (response.url().startsWith(new URL(base).origin) && response.status() >= 400) missing.push(response.url()); });
const ring = 'Rarity: Rare\nHosted Test Ring\nGold Ring\n--------\nItem Level: 84\n--------\n+70 to maximum Life\n+20% to Fire Resistance';
const xml = `<PathOfBuilding2><Build level="87" mainSocketGroup="1"/><Items activeItemSet="1"><Item id="1"><![CDATA[${ring}]]></Item><ItemSet id="1"><Slot name="Ring 1" itemId="1"/></ItemSet></Items><Skills activeSkillSet="1"><SkillSet id="1"><Skill enabled="true"><Gem nameSpec="Twister" level="18" enabled="true"/><Gem nameSpec="Projectile Acceleration III" level="1" enabled="true"/></Skill><Skill enabled="true"><Gem nameSpec="Explosive Spear" level="18" enabled="true"/></Skill><Skill enabled="true"><Gem nameSpec="Whirling Slash" level="18" enabled="true"/></Skill></SkillSet></Skills></PathOfBuilding2>`;
try {
  await page.goto(base);
  await expect(page.getByText('浏览器版 · 实际工坊', { exact: true })).toBeVisible();
  const input = page.getByRole('textbox', { name: 'PoB2 分享代码或 XML' });
  await input.fill(xml);
  await page.getByRole('button', { name: '预览 PoB2 装备', exact: true }).click();
  await page.getByRole('button', { name: '确认替换整套装备（1 件）' }).click();
  await page.getByRole('button', { name: '按默认开始', exact: true }).click();
  await expect(page.locator('.sr-slot')).toHaveCount(3);
  await page.locator('.sr-slot').first().getByRole('button').first().click();
  await expect.poll(() => page.locator('.sr-slot img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true);
  await page.getByRole('button', { name: /左戒指：/ }).click();
  await page.getByRole('button', { name: '寻找这件的升级', exact: true }).click();
  const link = page.getByRole('link', { name: '官网检索提升候选 ↗', exact: true });
  await expect(link).toBeVisible();
  const tradeUrl = new URL(await link.getAttribute('href'));
  assert.equal(tradeUrl.host, 'www.pathofexile.com');
  assert(JSON.parse(tradeUrl.searchParams.get('q')).query.stats.length > 0);
  await page.getByRole('navigation', { name: '工作区域' }).getByRole('button', { name: '交易追踪' }).click();
  await expect(page.getByRole('heading', { name: '官方成交同步 · 本地版功能' })).toBeVisible();
  await expect(page.getByRole('button', { name: '读取最近 30 天日志' })).toBeDisabled();
  await page.getByRole('navigation', { name: '工作区域' }).getByRole('button', { name: '制作策略' }).click();
  await page.getByRole('button', { name: '粘贴游戏物品', exact: true }).click();
  await page.getByRole('button', { name: '试用戒指示例' }).click();
  await page.getByRole('button', { name: '计算制作策略', exact: true }).click();
  await expect(page.locator('.wb-results')).toBeVisible({ timeout: 60000 });
  await expect(page.locator('.wb-results')).toContainText(/目标已达成|可以停止制作/);
  assert.equal(await page.locator('.wb-results .wb-metrics>div').first().locator('strong').innerText(), '0');
  await mkdir('artifacts/workbench', { recursive: true });
  await page.screenshot({ path: 'artifacts/workbench/hosted-desktop.png' });
  await page.getByRole('navigation', { name: '工作区域' }).getByRole('button', { name: '角色装备' }).click();
  await page.reload();
  await expect(page.locator('.sr-slot')).toHaveCount(3);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/workbench/hosted-mobile.png' });
  assert.deepEqual(errors, []); assert.deepEqual(apiRequests, []); assert.deepEqual(missing, []);
  console.log('PASS hosted app: explicit PoB import, real skills/art, native joint trade query, desktop boundaries, real worker calculation, persistence, mobile and nested assets; no backend requests.');
} finally { await browser.close(); }
