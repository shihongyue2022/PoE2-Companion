import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } }), errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.goto(process.env.WORKBENCH_URL ?? 'http://127.0.0.1:5173/?companion=1');
  await expect(page.getByRole('region', { name: '角色全身装备' })).toBeVisible();
  const fixture = await page.evaluate(async () => {
    const { damageState } = await import('/src/workbench/fixtures/damageGoal.ts');
    const { MORIOR_INVICTUS_SAMPLE } = await import('/src/workbench/fixtures/moriorInvictus.ts');
    const { equipmentSignature } = await import('/src/workbench/characterPanel.ts');
    const boots = 'Item Class: Boots\nRarity: Rare\nOld Boots\nSilk Slippers\n--------\n+30% to Fire Resistance\n31% increased Movement Speed\n10% increased Attack Speed';
    const nextBoots = 'Item Class: Boots\nRarity: Rare\nNew Boots\nSilk Slippers\n--------\n+38% to Cold Resistance\n+20% to Chaos Resistance\n30% increased Attack Speed';
    const state = damageState(); state.character = undefined;
    state.slots = { body: MORIOR_INVICTUS_SAMPLE.replace('全元素抗性+10(8-10)%', '混沌抗性+10(8-10)%'), boots };
    state.source.equipmentSignature = equipmentSignature(state.slots);
    state.source.reference = { values: { fireResistance: 120, coldResistance: 110, lightningResistance: 100, chaosResistance: 90 }, caps: { fireResistance: 75, coldResistance: 75, lightningResistance: 75, chaosResistance: 75 } };
    localStorage.setItem('poe2-workbench-loadout-v1', JSON.stringify(state));
    return { body: MORIOR_INVICTUS_SAMPLE, boots: nextBoots };
  });
  await page.reload();
  const loadout = page.getByRole('region', { name: '角色全身装备' });
  await loadout.getByRole('navigation').getByRole('button', { name: /^比较候选/ }).click();
  await loadout.getByLabel('粘贴候选装备').fill(fixture.body);
  const comparison = loadout.getByRole('region', { name: '比较替换装备' });
  await comparison.getByRole('button', { name: '按两件全部镶嵌比较' }).click();
  await expect(comparison.getByRole('article', { name: '混沌抗性' }).getByText('总值：90% → 40%')).toBeVisible();
  await expect(comparison.getByText('混沌抗性未达上限，暂不推荐更换')).toBeVisible();
  await comparison.getByRole('button', { name: '采用候选并替换胸甲' }).click();
  await expect(loadout.getByRole('region', { name: '当前整套抗性' })).toContainText('混沌抗性：40% / 75%');
  await page.reload();
  await expect(loadout.getByRole('region', { name: '当前整套抗性' })).toContainText('混沌抗性：40% / 75%');
  await loadout.getByRole('navigation').getByRole('button', { name: /^比较候选/ }).click();
  await loadout.getByLabel('粘贴候选装备').fill(fixture.boots);
  const gate = comparison.getByRole('region', { name: '全身四抗换装检查' });
  await expect(gate.getByRole('article', { name: '火焰抗性' }).getByText('有效：75% → 75% · 上限 75%')).toBeVisible();
  await expect(gate.getByRole('article', { name: '火焰抗性' }).getByText('总值：170% → 140%')).toBeVisible();
  await expect(gate.getByRole('article', { name: '混沌抗性' }).getByText('总值：40% → 60%')).toBeVisible();
  await expect(gate.getByRole('article', { name: '混沌抗性' }).getByText('混沌抗性 · 缺 15%')).toBeVisible();
  await expect(comparison.getByText('抗性未达上限，不符合配装目标', { exact: true })).toBeVisible();
  await mkdir('artifacts/workbench', { recursive: true });
  await gate.screenshot({ path: 'artifacts/workbench/whole-resistance-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await gate.screenshot({ path: 'artifacts/workbench/whole-resistance-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('PASS PoB baseline, chaos socket loss after body adoption/reload, independent chaos deficit after a second boots swap');
  console.log('PASS elemental overcap is spendable, effective fire stays capped, stronger attack speed cannot hide chaos deficit');
} finally { await browser.close(); }
